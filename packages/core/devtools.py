def gen_device_keys() -> Path:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec

    keydir = REPO_ROOT / "dev" / "keys"
    keydir.mkdir(parents=True, exist_ok=True)
    devices = []
    for device_id, owner, status in DEV_DEVICES:
        pem_path = keydir / f"{device_id}.private.pem"
        if pem_path.exists():
            priv = serialization.load_pem_private_key(pem_path.read_bytes(), password=None)
        else:
            priv = ec.generate_private_key(ec.SECP256R1())
            pem_path.write_bytes(
                priv.private_bytes(
                    serialization.Encoding.PEM,
                    serialization.PrivateFormat.PKCS8,
                    serialization.NoEncryption(),
                )
            )
            pem_path.chmod(0o600)
        spki = priv.public_key().public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo
        )
        devices.append(
            {
                "device_id": device_id,
                "owner_id": owner,
                "status": status,
                "curve": "P-256",
                "public_key_spki_b64u": _b64u(spki),
                "enrolled_at": "<TODAY-30d>",
                "family": "first_party",
            }
        )
    doc = {
        "_note": (
            "PUBLIC KEYS ONLY. Wire format is fixed by contracts/CRYPTO_WIRE_FORMAT.md: "
            "SPKI DER, base64url, no padding. Private keys live in gitignored dev/keys/ and "
            "never leave the browser in a real deployment."
        ),
        "devices": sorted(devices, key=lambda d: d["device_id"]),
    }
    out = CONTRACTS / "device_keys.json"
    out.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    return out


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "help"
    if cmd == "vectors":
        print("wrote", gen_vectors())
    elif cmd == "device-keys":
        print("wrote", gen_device_keys())
    elif cmd == "golden":
        from .goldens import regenerate

        for p in regenerate():
            print("wrote", p)
    elif cmd == "policy":
        from .policy.version import policy_hash, policy_version

        print(f"policy_version={policy_version()} policy_hash={policy_hash()}")
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
