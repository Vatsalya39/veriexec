            "separators are ',' and ':' with no whitespace",
            "ensure_ascii = false: emit real UTF-8, never \\uXXXX for printable characters",
            "normalise every string AND every key to Unicode NFC before serialising",
            "a null value becomes the sentinel string U+0000, which JSON escapes to \\u0000",
            "money is an integer number of minor units; a float is an error, not a rounding",
            "timestamps are ISO-8601 strings with an explicit offset, never datetime objects",
            "an absent key is an error in a fingerprint pre-image; pass an explicit null",
